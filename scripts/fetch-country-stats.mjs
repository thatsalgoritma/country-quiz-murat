import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import worldCountries from "world-countries";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const PROJECT_ROOT = path.resolve(__dirname, "..");
const OUTPUT_FILE = path.join(
  PROJECT_ROOT,
  "src",
  "data",
  "countryStats.ts",
);

const INDICATORS = {
  population: "SP.POP.TOTL",
  gdp: "NY.GDP.MKTP.CD",
  gdpPerCapita: "NY.GDP.PCAP.CD",
};

async function fetchIndicator(indicator) {
  const url =
    `https://api.worldbank.org/v2/country/all/indicator/${indicator}` +
    `?format=json&per_page=400&mrnev=1`;

  console.log(`Fetching ${indicator}...`);

  const response = await fetch(url);

  if (!response.ok) {
    throw new Error(
      `World Bank API error for ${indicator}: ${response.status} ${response.statusText}`,
    );
  }

  const data = await response.json();

  if (!Array.isArray(data) || !Array.isArray(data[1])) {
    throw new Error(`Unexpected World Bank response for ${indicator}`);
  }

  const values = new Map();

  for (const item of data[1]) {
    const cca3 = item.countryiso3code;

    if (!cca3) continue;

    const value =
      typeof item.value === "number"
        ? item.value
        : item.value != null
          ? Number(item.value)
          : null;

    const year = item.date ? Number(item.date) : null;

    if (value != null && Number.isFinite(value)) {
      values.set(cca3, {
        value,
        year: Number.isFinite(year) ? year : null,
      });
    }
  }

  console.log(`  ${values.size} countries found`);

  return values;
}

function createCountryList() {
  return worldCountries
    .filter(
      (country) =>
        country.capital &&
        country.capital.length > 0 &&
        country.latlng &&
        country.independent &&
        country.cca3,
    )
    .map((country) => ({
      cca3: country.cca3,
      name: country.name.common,
    }))
    .sort((a, b) => a.name.localeCompare(b.name));
}

function formatNumber(value) {
  if (value == null) return "null";

  if (!Number.isFinite(value)) {
    return "null";
  }

  return String(Math.round(value));
}

function generateTypeScript(countries, population, gdp, gdpPerCapita) {
  const rows = countries.map((country) => {
    const populationData = population.get(country.cca3);
    const gdpData = gdp.get(country.cca3);
    const gdpPerCapitaData = gdpPerCapita.get(country.cca3);

    return `  ${JSON.stringify(country.cca3)}: {
    population: {
      value: ${formatNumber(populationData?.value)},
      year: ${populationData?.year ?? "null"},
    },
    gdp: {
      value: ${formatNumber(gdpData?.value)},
      year: ${gdpData?.year ?? "null"},
    },
    gdpPerCapita: {
      value: ${formatNumber(gdpPerCapitaData?.value)},
      year: ${gdpPerCapitaData?.year ?? "null"},
    },
  },`;
  });

  return `// AUTO-GENERATED FILE.
// Do not edit manually.
// Generated by scripts/fetch-country-stats.mjs

export interface CountryStatValue {
  value: number | null;
  year: number | null;
}

export interface CountryStats {
  population: CountryStatValue;
  gdp: CountryStatValue;
  gdpPerCapita: CountryStatValue;
}

export const countryStats: Record<string, CountryStats> = {
${rows.join("\n")}
};
`;
}

async function main() {
  console.log("🌍 Fetching World Bank country statistics...\n");

  const [population, gdp, gdpPerCapita] = await Promise.all([
    fetchIndicator(INDICATORS.population),
    fetchIndicator(INDICATORS.gdp),
    fetchIndicator(INDICATORS.gdpPerCapita),
  ]);

  const countries = createCountryList();

  const output = generateTypeScript(
    countries,
    population,
    gdp,
    gdpPerCapita,
  );

  await fs.mkdir(path.dirname(OUTPUT_FILE), { recursive: true });
  await fs.writeFile(OUTPUT_FILE, output, "utf8");

  console.log("\n✅ countryStats.ts created.");
  console.log(`📁 ${OUTPUT_FILE}`);
  console.log(`🌍 Countries included: ${countries.length}`);
}

main().catch((error) => {
  console.error("\n❌ Failed to fetch country statistics.");
  console.error(error);
  process.exit(1);
});